import { buildTrack } from '../track.js';

function makeTrack(opts) {
  const segments = [
    { type: 'flat', length: 160, surface: opts.startSurface || 'asphalt' },
    ...opts.segments,
    { type: 'checkpoint' },
    { type: 'flat', length: 140, surface: opts.startSurface || 'asphalt' },
  ];
  const built = buildTrack(0, 500, segments);
  return {
    id: opts.id,
    name: opts.name,
    tagline: opts.tagline,
    theme: opts.theme,
    difficulty: opts.difficulty,
    parTimes: opts.parTimes,
    unlockRequires: opts.unlockRequires || null,
    ...built,
  };
}

