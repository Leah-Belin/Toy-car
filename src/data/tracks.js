import { buildTrack } from '../track.js';

function makeTrack(opts) {
  const surface = opts.startSurface || 'asphalt';
  const segments = [
    { type: 'flat', length: 160, surface },
    ...opts.segments,
    { type: 'checkpoint' },
    // A long, obstacle-free tail past the last hazard: reaching the
    // milestone (and beyond, for a great run) should never mean driving
    // off the end of designed content into nothing.
    { type: 'flat', length: 900, surface },
  ];
  const built = buildTrack(0, 500, segments);
  return {
    id: opts.id,
    name: opts.name,
    tagline: opts.tagline,
    theme: opts.theme,
    difficulty: opts.difficulty,
    // Meters of distance needed to unlock the next track. Every track's
    // hazard section is authored to comfortably clear this before the
    // flat tail even starts, fixed and identical every run.
    milestoneMeters: opts.milestoneMeters,
    unlockRequires: opts.unlockRequires || null,
    ...built,
  };
}

